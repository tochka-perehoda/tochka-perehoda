function showScreen(name) {

  document
    .querySelectorAll('.screen')
    .forEach(screen => {
      screen.classList.remove('active');
    });

  const target = document.getElementById(
    'screen-' + name
  );

  if (target) {
    target.classList.add('active');
  }

  if (name === 'test') {
    renderTest();
  }

  if (name === 'transition') {
    renderTransition();
  }

  window.scrollTo(0, 0);
}


