function renderTest() {

  const wrap = document.getElementById('test-wrap');

  if (!wrap) return;

  if (answers.length === questions.length) {
    renderResult();
    return;
  }

  const i = answers.length;

  wrap.innerHTML = `

    <div class="progress">
      ВОПРОС ${i + 1} ИЗ ${questions.length}
    </div>

    <div class="question">

      <h3>
        ${questions[i].t}
      </h3>

      <div class="answers">

        ${questions[i].a.map((text, index) => `

          <button
            class="answer"
            onclick="choose(${index})"
          >
            ${String.fromCharCode(65 + index)}. ${text}
          </button>

        `).join('')}

      </div>

    </div>

  `;
}


/* =========================================================
   ОТВЕТ НА ВОПРОС
   ========================================================= */

function choose(index) {

  answers.push(index);

  renderTest();

}


/* =========================================================
   ОПРЕДЕЛЕНИЕ РЕЗУЛЬТАТА
   ========================================================= */

function calculateStage() {

  const counts = [0, 0, 0, 0];

  answers.forEach(answer => {

    /*
      0 = Автопилот
      1 = Толчок
      2 = Пробуждение
      3 и 4 = Творец
    */

    if (answer === 0) {
      counts[0]++;
    }

    if (answer === 1) {
      counts[1]++;
    }

    if (answer === 2) {
      counts[2]++;
    }

    if (answer === 3 || answer === 4) {
      counts[3]++;
    }

  });


  const max = Math.max(...counts);

  const index = counts.indexOf(max);

  return stages[index];

}


